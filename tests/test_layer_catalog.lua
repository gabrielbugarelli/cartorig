local root=assert(arg[1]);local Layer=dofile(root..'/src/cartorig/layer_catalog.lua')
local Json=dofile(root..'/src/cartorig/json.lua')
local path=root..'/tests/fixtures/layer_index'
local idx=Layer.load_index(path,'land',Json)
assert(idx.schema=='cartorig.offline.layers/1' and #idx.features==2)
local left=Layer.query(idx,{-62,-21,-35,5})
assert(#left==1 and left[1].id=='test:land:0')
local island=Layer.query(idx,{29,9,33,12})
assert(#island==1 and island[1].id=='test:land:1')
local wrapped=Layer.query(idx,{170,-30,-170,20})
assert(#wrapped==0)
local first=Layer.load_feature(path,idx,left[1],Json)
assert(first.geometry.type=='Polygon' and first.properties.NAME=='continent')
local second=Layer.load_feature(path,idx,island[1],Json)
assert(second.properties.NAME=='island' and second.geometry.coordinates[1][1][1]==30)
assert(not pcall(function()Layer.load_index(path,'../../etc',Json)end))
assert(not pcall(function()Layer.query(idx,{-190,0,180,40})end))
assert(not pcall(function()Layer.query(idx,{0,80,100,70})end))
assert(not pcall(function()Layer.query(idx,{-180,-90,180,90},0)end))
assert(not pcall(function()
  Layer.load_feature(path,{dataset='land',featureFile='../private'},left[1],Json)
end))
assert(not pcall(function()
  Layer.load_feature(path,idx,{geometryType='Polygon',featureOffset=100000000,
    featureBytes=50},Json)
end))
print('PASS indexed offline base geometry: deterministic seek, viewport, wrap and path safety')
