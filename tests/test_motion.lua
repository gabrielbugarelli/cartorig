local root=assert(arg[1],'pass repository root')
local scene=dofile(root..'/src/cartorig/scene.lua')
local motion=dofile(root..'/src/cartorig/motion.lua')
local s=scene.new('scene-0001')
local br=scene.add_location(s,{id='ne:br',name='Brazil',geometryType='MultiPolygon',type='Country'},'Region')
local r=motion.prepare(br,'MO-REG-04',{start=330,frameCount=900,targetColor='#00FF00'}, {})
assert(r.first==330 and r.last==330 and r.channels.fill[1].interpolation=='Step')
assert(#r.channels.fill==2)
assert(r.channels.fill[1].frame==329 and r.channels.fill[1].value==br.style.fill)
assert(r.channels.fill[2].frame==330 and r.channels.fill[2].value=='#00FF00')
assert(not pcall(function()motion.prepare(br,'MO-REG-04',{start=330,frameCount=900,targetColor='#00FF00'}, {fill={{frame=0,value='#FF0000'}}})end))
local fade=motion.prepare(br,'MO-REG-01',{start=100,frameCount=900},{})
assert(fade.channels.opacity[1].value==0 and fade.channels.opacity[2].value==100)
assert(fade.last==124)
local col=motion.prepare(br,'MO-REG-03',{start=100,frameCount=900,targetColor='#20A65A'}, {opacity=fade.channels.opacity})
assert(col.channels.fill[2].value=='#20A65A')
fade.originalFingerprint='hash-before'
assert(motion.mark_custom(fade,'hash-after')=='PRESET_CUSTOMIZED')
local camera=s.objects[2]
local fly=motion.prepare(camera,'MO-CAM-01',{start=0,frameCount=900,targetPose={longitude=-47,latitude=-15,zoom=4}}, {})
assert(#fly.channels.longitude==2 and #fly.channels.latitude==2 and #fly.channels.zoom==2)
local pulse=motion.prepare(br,'MO-REG-06',{start=100,frameCount=900},{})
assert(pulse.last==136 and #pulse.channels.highlightStrength==5)
local count=0 for _ in pairs(motion.definitions) do count=count+1 end
assert(count==16)
assert(not pcall(function()motion.prepare(br,'MO-REG-01',{start=899,frameCount=900}, {})end))
print('PASS motion: 16 definitions, instant change, fade, color, fly-to, pulse, conflict and bounds')
