local root=assert(arg[1]);local Scene=dofile(root..'/src/cartorig/scene.lua')
local Ops=dofile(root..'/src/cartorig/scene_ops.lua')
local state=Scene.new('nested-group-locks-01')
local marker=Scene.add_location(state,{id='city:1',name='Location',type='City',point={lon=-46,lat=-23}},'Marker')
local route=Scene.add_route(state,{lon=-45,lat=-22},{lon=-42,lat=-20})
local outer=Scene.add_group(state,'Outer')
local inner=Scene.add_group(state,'Inner')
inner.groupId=outer.id
marker.groupId=inner.id
route.groupId=inner.id
assert(Scene.validate(state))
Scene.set_lock(state,outer.id,true)
local function blocked(fn,label)
  local ok,err=pcall(fn)
  assert(not ok and tostring(err):lower():find('lock'),label..': '..tostring(err))
end
blocked(function()Scene.set_lock(state,marker.id,true)end,'lock toggle under locked parent')
blocked(function()Scene.set_lock(state,inner.id,true)end,'inner group lock toggle')
blocked(function()Ops.update_route(state,route.id,{curvature=25})end,'route geometry')
blocked(function()Ops.reverse_route(state,route.id)end,'route reversal')
blocked(function()Ops.create_group(state,Scene,'New',{marker.id})end,'group operation')
assert(route.route.curvature==0)
Scene.set_lock(state,outer.id,false)
Scene.set_lock(state,inner.id,true)
blocked(function()Ops.update_route(state,route.id,{curvature=33})end,'nested locked group')
Scene.set_lock(state,inner.id,false)
Ops.update_route(state,route.id,{curvature=33,pathType='Curved'})
assert(route.route.curvature==33 and Scene.validate(state))
print('PASS nested Group lock: Scene and Route operations respect all ancestors')
