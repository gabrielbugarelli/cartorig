local root=assert(arg[1]);local core=dofile(root..'/src/cartorig/scene.lua');local ops=dofile(root..'/src/cartorig/scene_ops.lua')
local s=core.new('test-scene-001')
local city={id='sao-paulo-city',name='São Paulo',type='City',point={lon=-46.63,lat=-23.55}}
local p=core.add_location(s,city,'Marker')
local p2=core.duplicate(s,p.id)
local group=ops.create_group(s,core,'My markers',{p.id,p2.id})
assert(p.groupId==group.id and p2.groupId==group.id)
core.set_lock(s,group.id,true)
assert(not pcall(function()core.set_style(s,p.id,'fill','#123456')end))
core.set_lock(s,group.id,false)
ops.ungroup(s,group.id)
assert(not p.groupId and not p2.groupId)
local r=core.add_route(s,{lon=-47,lat=-15},{lon=-50,lat=0})
ops.update_route(s,r.id,{waypoints={{lon=-48,lat=-5}},pathType='Curved',curvature=10,followerId=p.id})
assert(r.route.followerId==p.id)
assert(not pcall(function()ops.update_route(s,r.id,{waypoints={{lon=210,lat=0}}})end))
assert(r.route.waypoints[1].lon==-48,'invalid edit must be atomic')
ops.reverse_route(s,r.id)
assert(r.route.from.lon==-50 and r.route.to.lon==-47)
assert(ops.validate_groups(s))
print('PASS scene operations: group lifecycle, inherit lock, atomic route edits, follower refs and reversed waypoints')
