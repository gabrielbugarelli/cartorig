local root=assert(arg[1])
local Scene=dofile(root..'/src/cartorig/scene.lua')
local Ops=dofile(root..'/src/cartorig/scene_ops.lua')
local Geo=dofile(root..'/src/cartorig/geo.lua')
local s=Scene.new('waypoint-authoring-0001')
local r=Scene.add_route(s,{lon=-48,lat=-16},{lon=-51,lat=0})
local originalId=r.id
local edited=Ops.update_route(s,r.id,{pathType='Curved',curvature=55,
 waypoints={{lon=-49,lat=-8},{lon=-50,lat=-4}}})
assert(edited==r and r.id==originalId and #r.route.waypoints==2)
local samples=Geo.route_samples(r.route,16)
assert(#samples==49,'three Curve segments must preserve all sample endpoints')
Scene.validate(s)
assert(not pcall(function()Ops.update_route(s,r.id,{curvature=101})end))
assert(#r.route.waypoints==2 and r.route.curvature==55)
local ui=assert(io.open(root..'/fusion/CartoRig Scene.lua','r')):read('*a')
assert(ui:find('CR_AddWaypoint',1,true) and ui:find('CR_ClearWaypoints',1,true))
assert(ui:find('engine:add_route(routeFrom,routeTo,route_options())',1,true))
assert(ui:find('engine:update_route(selected_id,changes)',1,true))
print('PASS editable Route: custom waypoints, curved controls, persistent identity and bounds')
