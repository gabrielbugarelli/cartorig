local root=assert(arg[1]);local Scene=dofile(root..'/src/cartorig/scene.lua')
local s=Scene.new('schema-hardening-1')
local r=Scene.add_route(s,{lon=-48,lat=-16},{lon=-51,lat=2})
local c=Scene.add_location(s,{id='city:1',name='Brasilia',type='City',point={lon=-48,lat=-16}},'Marker')
local function corrupted(change)
 local snap=Scene.snapshot(s);change(snap)
 assert(not pcall(function() Scene.validate(snap)end),'corrupted scene must fail validation')
end
assert(Scene.validate(s))
corrupted(function(x)x.objects[3].route.pathType='Great-circle' end)
corrupted(function(x)x.objects[3].route.curvature=math.huge end)
corrupted(function(x)x.objects[3].route.waypoints={{lon=200,lat=0}}end)
corrupted(function(x)x.objects[3].route.from={lon=-48,lat=-16};x.objects[3].route.to={lon=-48,lat=-16}end)
corrupted(function(x)x.objects[4].anchor.lon=math.huge end)
corrupted(function(x)x.objects[2].style.zoom=0 end)
corrupted(function(x)x.objects[2].style.zoom=100 end)
corrupted(function(x)x.objects[4].style.size=1000 end)
corrupted(function(x)x.objects[4].id='other:Marker:10000' end)
assert(not pcall(function()Scene.set_style(s,s.objects[2].id,'zoom',0)end))
assert(not pcall(function()Scene.set_style(s,c.id,'size',math.huge)end))
assert(Scene.validate(s) and Scene.get(s,r.id)==r)
print('PASS persisted Scene shape, route, camera and numeric invariants')
