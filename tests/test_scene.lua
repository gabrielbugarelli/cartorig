local root=assert(arg[1],'pass repository root')
local scene=dofile(root..'/src/cartorig/scene.lua')
local s=scene.new('scene-0001','natural-earth-10m-2026')
assert(#s.objects==2)
local state={id='ne:br-rj',name='Rio de Janeiro',type='State',geometryType='MultiPolygon',version='1',dataset='admin1'}
local city={id='ne:br-rj-city',name='Rio de Janeiro',type='City',point={lon=-43.2,lat=-22.9},version='1'}
local rio=scene.add_location(s,state,'Region')
local pin=scene.add_location(s,city,'Marker')
assert(rio.id~=pin.id and rio.kind=='Region' and pin.kind=='Marker')
local ok=pcall(function()scene.add_location(s,city,'Region')end)
assert(not ok,'city point must never become municipal polygon')
scene.set_style(s,rio.id,'fill','#C92A2A')
scene.set_style(s,pin.id,'fill','#20A65A')
assert(rio.style.fill=='#C92A2A' and pin.style.fill=='#20A65A')
assert(not pcall(function()scene.set_style(s,rio.id,'fill','not-hex')end))
local duplicate=scene.duplicate(s,rio.id)
scene.set_style(s,duplicate.id,'fill','#123456')
assert(rio.style.fill=='#C92A2A' and duplicate.id~=rio.id)
scene.rename(s,duplicate.id,'Rio Copy')
assert(scene.get(s,duplicate.id).name=='Rio Copy')
local route=scene.add_route(s,{lon=-47.9,lat=-15.7},{lon=-51.7,lat=1.4})
route.route.followerId=pin.id
assert(not pcall(function()scene.remove(s,pin.id)end),'referenced marker cannot be deleted')
scene.set_lock(s,rio.id,true)
assert(not pcall(function()scene.set_style(s,rio.id,'fill','#111111')end))
scene.set_lock(s,rio.id,false)
scene.reorder(s,duplicate.id,3)
assert(scene.validate(s))
local snap=scene.snapshot(s)
snap.objects[3].name='Mutated copy'
assert(s.objects[3].name~='Mutated copy','snapshot must be independent')
scene.remove(s,duplicate.id)
assert(scene.validate(s))
print('PASS scene: typed locations, independent styles, CRUD, dependencies, lock, reorder, snapshot')
